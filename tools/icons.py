def main(package: pathlib.Path) -> None:
    from fontTools import subset

    root = pathlib.Path(__file__).resolve().parent.parent
    codepoints = json.loads((package / "font" / "codepoints.json").read_text())
    pairs = [line.split() for line in ICONS.strip().splitlines()]
    glyphs = {app: codepoints[lucide] for app, lucide in pairs}
    out = root / "resources" / "icons"
    out.mkdir(parents=True, exist_ok=True)
    options = subset.Options()
    options.layout_features = []
    options.name_IDs = ["*"]
    font = subset.load_font(str(package / "font" / "lucide.ttf"), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=sorted(set(glyphs.values())))
    subsetter.subset(font)
    subset.save_font(font, str(out / "lucide.ttf"), options)
    (out / "LICENSE").write_text((package / "LICENSE").read_text())
    entries = ",\n".join(f'    "{app}": "\\u{cp:04x}"' for app, cp in glyphs.items())
    (root / "style" / "Icons.js").write_text(
        ".pragma library\n\n"
        "// Generated by tools/icons.py from Lucide (resources/icons/LICENSE). App name → glyph.\n"
        f"var glyphs = {{\n{entries}\n}}\n"
        'function glyph(name) { return glyphs[name] || "" }\n'
    )
    print(f"{len(glyphs)} icons, {(out / 'lucide.ttf').stat().st_size} bytes")


if __name__ == "__main__":
    main(pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "package"))
