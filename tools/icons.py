#!/usr/bin/env python3
"""Regenerate the bundled icon font and qml/Icons.js from Lucide (ISC license).

Only the icons listed below are kept, so the font stays small. To add an icon:
add "app-name lucide-name" to ICONS, then run

    npm pack lucide-static && tar xzf lucide-static-*.tgz
    python3 -m pip install fonttools
    python3 tools/icons.py package

One icon per meaning: reuse an existing app name before adding a new one.
"""
